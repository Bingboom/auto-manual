"""Export complete reviewed panels without off-crop source-page paths.

Input PDFs come from this package's panel-recipe.json through asset_intake.
The existing native selector preserves original paths, clip groups, images,
opacity and transforms. The one-point selection margin retains edge strokes;
the SVG viewBox remains the exact reviewed crop. Verify against the input PDF
at 12x before admitting generated bytes.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

import pymupdf as fitz

PACKAGE = Path(__file__).resolve().parents[1]
REPO = next(p for p in PACKAGE.parents if (p / "build.py").is_file())
sys.path.insert(0, str(REPO))
from tools.asset_pipeline.native_svg import native_art_svg  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--panels-dir", type=Path, required=True)
    args = parser.parse_args()
    # MuPDF's SVG reader expects the conventional xlink prefix for images.
    ET.register_namespace("xlink", "http://www.w3.org/1999/xlink")
    ET.register_namespace("inkscape", "http://www.inkscape.org/namespaces/inkscape")
    figures = json.loads((PACKAGE / "source/figures.json").read_text())
    for figure in figures:
        if "clip_points" not in figure:
            continue
        pdf = args.panels_dir / f"{figure['slot']}.pdf"
        destination = (PACKAGE / figure["local_path"]).resolve()
        if not destination.is_relative_to(PACKAGE / "assets"):
            raise ValueError("panel destination escapes assets")
        with fitz.open(pdf) as document:
            if len(document) != 1:
                raise ValueError(f"expected one-page source panel: {pdf}")
            page = document[0]
            crop = fitz.Rect(page.rect)
            margin = crop + (-1, -1, 1, 1)
            indices = [i for i, drawing in enumerate(page.get_drawings())
                       if drawing["rect"].intersects(margin)]
            destination.write_bytes(native_art_svg(page, indices, list(crop)))
            print(figure["slot"], destination.stat().st_size)


if __name__ == "__main__":
    main()
